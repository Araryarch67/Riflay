import 'dart:convert';
import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:riflay/services/matugen_theme.dart';

const dark = {
  'primary': '#b8c4ff',
  'on_primary': '#192b6a',
  'surface': '#10131b',
  'on_surface': '#e1e2ec',
  'surface_container': '#20232b',
  'error': '#ffb4ab',
  'secondary': '#c3c5dd',
};
const light = {'primary': '#4355a4', 'surface': '#faf8ff', 'on_surface': '#1a1b23'};

void main() {
  test('accepts colors generated by the installed Matugen v4 CLI', () {
    final colors = MatugenColors.parse(File('test/fixtures/matugen-v4.json').readAsStringSync());
    expect(colors.scheme(light: false).primary, const Color(0xff9ccbfb));
    expect(colors.scheme(light: true).primary, const Color(0xff30628c));
    expect(colors.scheme(light: false).brightness, Brightness.dark);
    expect(colors.scheme(light: true).brightness, Brightness.light);
  });

  test('reads flat, camelCase and old mode-first Matugen output', () {
    for (final input in [
      dark,
      {
        'colors': {'dark': dark, 'light': light},
      },
      {'primary': '#b8c4ff', 'surface': '#10131b', 'onSurface': '#e1e2ec'},
    ]) {
      final parsed = MatugenColors.parse(jsonEncode(input));
      final scheme = parsed.scheme(light: false);
      expect(scheme.primary, const Color(0xFFb8c4ff));
      expect(scheme.onSurface, const Color(0xFFe1e2ec));
      expect(scheme.brightness, Brightness.dark);
    }
    final parsed = MatugenColors.parse(
      jsonEncode({
        'colors': {'dark': dark, 'light': light},
      }),
    );
    expect(parsed.scheme(light: true).brightness, Brightness.light);
    expect(parsed.scheme(light: false).error, const Color(0xFFffb4ab));
  });

  test('single-mode exports work in either mode, and a corrupt alternate mode is rejected', () {
    final single = MatugenColors.parse(
      jsonEncode({
        'colors': {'dark': dark},
      }),
    );
    expect(single.scheme(light: true).primary, const Color(0xFFb8c4ff));
    expect(
      () => MatugenColors.parse(
        jsonEncode({
          'colors': {
            'dark': dark,
            'light': {'primary': 'bad'},
          },
        }),
      ),
      throwsFormatException,
    );
  });

  test('current role-first output supports mode objects and hex/color values', () {
    final input = {
      'colors': {
        for (final key in dark.keys)
          key: {
            'dark': {'color': dark[key]},
            'light': {'hex': light[key] ?? dark[key]},
          },
      },
    };
    final colors = MatugenColors.parse(jsonEncode(input));
    expect(colors.scheme(light: false).surface, const Color(0xFF10131b));
    expect(colors.scheme(light: true).primary, const Color(0xFF4355a4));
    expect(() => MatugenColors.parse('{"primary":"oops"}'), throwsFormatException);
  });

  test('reload survives atomic replacement and invalid writes, and discovers a late file', () async {
    final dir = Directory.systemTemp.createTempSync('riflay-matugen-');
    final file = File('${dir.path}/colors.json');
    final theme = MatugenTheme(candidates: [file.path]);
    addTearDown(() {
      theme.dispose();
      dir.deleteSync(recursive: true);
    });
    await theme.reload();
    expect(theme.error, isNotNull);
    file.writeAsStringSync(jsonEncode(dark));
    await theme.reload();
    expect(theme.error, isNull);
    final lastGood = theme.colors;
    file.writeAsStringSync('{');
    await theme.reload();
    expect(theme.colors, same(lastGood));
    expect(theme.error, isNotNull);
    File('${dir.path}/new.json').writeAsStringSync(jsonEncode({...dark, 'primary': '#ffffff'}));
    File('${dir.path}/new.json').renameSync(file.path);
    await theme.reload();
    expect(theme.error, isNull);
    expect(theme.colors!.scheme(light: false).primary, Colors.white);
  });
}
